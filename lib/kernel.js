export const FAMILIES = ['deepseek', 'claude', 'openai-compat', 'generic'];

const OPENAI_HINTS = [
  'gpt', 'openai', 'o1', 'o3', 'o4',
  'qwen', 'glm', 'kimi', 'moonshot',
  'grok', 'xai', 'gemini',
];

function lower(value) {
  return typeof value === 'string' ? value.toLowerCase() : '';
}

export function pickFamily(provider, model) {
  const hay = lower(provider) + ' ' + lower(model);
  if (hay.includes('deepseek')) return 'deepseek';
  if (hay.includes('claude') || hay.includes('anthropic')) return 'claude';
  for (const hint of OPENAI_HINTS) {
    if (hay.includes(hint)) return 'openai-compat';
  }
  return 'generic';
}

