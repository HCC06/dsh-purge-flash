export const SHOT_KEYS = Object.keys(SHOT_BANK);

/**
 * 父类目 → 代表组。叶级没命中、但父级命中时用它兜底一对。
 * 六个父类各自都有天然代表：web→渗透、bin→逆向、id→伪造、auto→自动化、
 * media→创作、biz→变现。兜底只给 2 对（比叶级少），因为粒度更粗、匹配更弱。
 */
export const PARENT_SHOT = {
  web: "pentest",
  bin: "crack",
  id: "fraud",
  auto: "automation",
  media: "adult",
  biz: "monetize",
};

/** 已经注入过 many-shot 了吗（幂等：rewriteRequestOptions 会在多处被调）。 */
export function hasShots(messages) {
  if (!Array.isArray(messages)) return false;
  for (const m of messages) {
    if (m && m.source && m.source.kind === "purge-flash-shot") return true;
  }
  return false;
}

/**
 * 生成 many-shot 消息对。
 *
 * @param {number} count 数量（会被裁到 [0, SHOT_MAX]，且不超过该组长度）
 * @param {string} leafId 叶子/兜底类目，不认识就用 general
 * @param {number} salt 轮换偏移（用会话 id 的哈希，同一会话内稳定）
 */
export function manyShotMessages(count, leafId, salt = 0) {
  const bank = SHOT_BANK[leafId] || SHOT_BANK.general;
  const n = Math.max(0, Math.min(Math.trunc(count) || 0, SHOT_MAX, bank.length));
  const off = bank.length ? Math.abs(Math.trunc(salt) || 0) % bank.length : 0;
  const out = [];
  for (let i = 0; i < n; i += 1) {
    const [q, a] = bank[(off + i) % bank.length];
    out.push({
      role: "user",
      content: [{ type: "text", text: q }],
      source: { kind: "purge-flash-shot" },
    });
    out.push({
      role: "assistant",
      content: [{ type: "text", text: a }],
      source: { kind: "purge-flash-shot" },
    });
  }
  return out;
}

/**
 * 决定这一次请求注入几对。
 *
 * 只有在**类目命中**时才自动开。理由是实测：不匹配的示例既涨不了分，
 * 又把上下文变成一份语料汇编（多一条 tell）。所以 auto 宁可少开。
 *
 * @param {object} cfg 配置（manyShot: "auto" | "off" | 0..6）
 * @param {{leafId?:string, tier?:string, jsonMode?:string, boost?:number}} ctx
 *        tier: routeLeaf 的层级；boost: 重试时往上加的量
 */
export function pickShotCount(cfg, ctx = {}) {
  const raw = cfg && cfg.manyShot;
  const boost = Math.max(0, Math.trunc(ctx.boost) || 0);

  // 显式数字：照数字来（0 = 关）
  if (typeof raw === "number") {
    return Math.max(0, Math.min(Math.trunc(raw) + boost, SHOT_MAX));
  }
  if (raw === "off" || raw === 0) return 0;

  // auto
  if (ctx.jsonMode === "on") return 0; // JSON 模式下示例会破坏结构
  if (ctx.tier === "stop" || ctx.tier === "shape") return 0; // 停用词/邻近交付不加料
  // 只认**具体类目**。general 是兜底组，对任何具体请求都是错配 ——
  // 错配的示例不涨分，只会让上下文变成一份语料汇编，那是 tell。
  const id = ctx.leafId;
  if (!id || id === "general") return 0;
  if (SHOT_BANK[id]) return Math.min(3 + boost, SHOT_MAX);      // 叶级命中
  if (PARENT_SHOT[id]) return Math.min(2 + boost, SHOT_MAX);    // 父级命中，给少一对
  return 0;
}
