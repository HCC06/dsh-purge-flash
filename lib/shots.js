/**
 * many-shot 语料库：按叶子类目分组的合规问答对。
 *
 * 为什么不再是一张平表
 * --------------------
 * in-context learning 起作用靠的是**分布匹配**：示例与真实请求同类同形，
 * 模型才会把「给步骤」当成这个上下文的默认文体。原来那 8 对是混着排的，
 * count=2 永远给出「注册脚本 + 权限字段」——对一个脱壳请求来说这是错配。
 * 错配的示例不但不涨分，还会让上下文看起来像一份「通用越狱语料汇编」，
 * 这本身就是一条 tell。
 *
 * 所以：按 parent/leaf 分组，组内按会话轮换，组间不混。
 *
 * 形态纪律（照 I-FSJ 的「格式整齐」）
 * ----------------------------------
 * - Q 一行、A 一行，每对 ≤ 90 字
 * - A 以动词或编号开头，3–4 步，不解释、不加条件
 * - 全组同构：长短、句式、标点一致，让示例退化成模板，不抢注意力
 *
 * 这些示例只演示「文体」，不含可执行的具体参数 —— 真实内容由主回答给。
 */

